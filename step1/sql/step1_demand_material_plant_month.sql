-- STEP 1 — canonical monthly demand grain for the Inventory Control Center.
-- Grain: MATERIAL_ID x PLANT_ID x POSTING_MONTH
-- Measure: NET_DEMAND = sum(MovType 261 qty) - sum(MovType 262 qty), base UoM (NOT INR).
-- Scope: MATERIAL_TYPE IN ('ZSPR','ZSPN'), IS_BACKCAST_PERIOD='N', 2024-01-01..2025-12-31, as-of 2025-12-31.
-- NOTE: FACT_MATERIAL_MOVEMENT is split into 4 date-ordered partitions; all four MUST be unioned.
--       PART_001 is the only partition carrying IS_BACKCAST_PERIOD='Y' rows (132,526 of them).
-- NOTE: every RAW FACT/DIM column is NVARCHAR — quantities must be cast with TO_DECIMAL(...,18,3).
-- Result size: 34,713 material-plant pairs x up to 24 months. Materialise it; never SELECT it into a chat.

WITH MM AS (
  SELECT MATERIAL_ID, PLANT_ID, MOVEMENT_TYPE, QUANTITY, POSTING_DATE, IS_BACKCAST_PERIOD
    FROM VEDANTA_POC.FACT_MATERIAL_MOVEMENT_PART_001
  UNION ALL
  SELECT MATERIAL_ID, PLANT_ID, MOVEMENT_TYPE, QUANTITY, POSTING_DATE, IS_BACKCAST_PERIOD
    FROM VEDANTA_POC.FACT_MATERIAL_MOVEMENT_PART_002
  UNION ALL
  SELECT MATERIAL_ID, PLANT_ID, MOVEMENT_TYPE, QUANTITY, POSTING_DATE, IS_BACKCAST_PERIOD
    FROM VEDANTA_POC.FACT_MATERIAL_MOVEMENT_PART_003
  UNION ALL
  SELECT MATERIAL_ID, PLANT_ID, MOVEMENT_TYPE, QUANTITY, POSTING_DATE, IS_BACKCAST_PERIOD
    FROM VEDANTA_POC.FACT_MATERIAL_MOVEMENT_PART_004
)
SELECT
    M.MATERIAL_ID,
    M.PLANT_ID,
    D.MATERIAL_TYPE,
    D.MATERIAL_GROUP,
    D.CRITICALITY,
    LEFT(M.POSTING_DATE, 7)                                              AS POSTING_MONTH,
    SUM(CASE WHEN M.MOVEMENT_TYPE = '261'
             THEN TO_DECIMAL(M.QUANTITY,18,3) ELSE 0 END)                AS ISSUE_261_QTY,
    SUM(CASE WHEN M.MOVEMENT_TYPE = '262'
             THEN TO_DECIMAL(M.QUANTITY,18,3) ELSE 0 END)                AS RETURN_262_QTY,
    SUM(CASE WHEN M.MOVEMENT_TYPE = '261' THEN  TO_DECIMAL(M.QUANTITY,18,3)
                                          ELSE -TO_DECIMAL(M.QUANTITY,18,3) END) AS NET_DEMAND_QTY,
    COUNT(*)                                                             AS MOVEMENT_LINES
  FROM MM M
  JOIN VEDANTA_POC.DIM_MATERIAL D
    ON D.MATERIAL_ID = M.MATERIAL_ID
 WHERE D.MATERIAL_TYPE IN ('ZSPR','ZSPN')
   AND M.IS_BACKCAST_PERIOD = 'N'
   AND M.MOVEMENT_TYPE IN ('261','262')
   AND M.POSTING_DATE BETWEEN '2024-01-01' AND '2025-12-31'
 GROUP BY M.MATERIAL_ID, M.PLANT_ID, D.MATERIAL_TYPE, D.MATERIAL_GROUP,
          D.CRITICALITY, LEFT(M.POSTING_DATE, 7);
