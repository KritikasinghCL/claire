-- STEP 1 — RAW vs CURATED reconciliation, as-of 2025-12-31.
-- Every figure in step1_data.json "reconciliation" comes from one of the four blocks below.

------------------------------------------------------------------------------
-- R1. Gross inventory (qty + value) and line count, per plant.
--     CURATED: INVENTORY_CLASSIFICATION, INVENTORY_KPI_MONTHLY(GROSS_INVENTORY_VALUE_INR)
--     RAW:     FACT_INVENTORY_SNAPSHOT_PART_001..003 x DIM_MATERIAL.UNIT_COST_INR
------------------------------------------------------------------------------
WITH SNAP AS (
  SELECT SNAPSHOT_DATE, MATERIAL_ID, PLANT_ID, CLOSING_QTY, IS_BACKCAST_PERIOD FROM VEDANTA_POC.FACT_INVENTORY_SNAPSHOT_PART_001
  UNION ALL SELECT SNAPSHOT_DATE, MATERIAL_ID, PLANT_ID, CLOSING_QTY, IS_BACKCAST_PERIOD FROM VEDANTA_POC.FACT_INVENTORY_SNAPSHOT_PART_002
  UNION ALL SELECT SNAPSHOT_DATE, MATERIAL_ID, PLANT_ID, CLOSING_QTY, IS_BACKCAST_PERIOD FROM VEDANTA_POC.FACT_INVENTORY_SNAPSHOT_PART_003),
RAWV AS (
  SELECT S.PLANT_ID,
         SUM(TO_DECIMAL(S.CLOSING_QTY,18,3))                                       AS QTY,
         SUM(TO_DECIMAL(S.CLOSING_QTY,18,3)*TO_DECIMAL(D.UNIT_COST_INR,18,4))       AS VAL,
         COUNT(*)                                                                   AS LINES
    FROM SNAP S JOIN VEDANTA_POC.DIM_MATERIAL D ON D.MATERIAL_ID = S.MATERIAL_ID
   WHERE D.MATERIAL_TYPE IN ('ZSPR','ZSPN') AND S.IS_BACKCAST_PERIOD='N'
     AND S.SNAPSHOT_DATE = '2025-12-31'
   GROUP BY S.PLANT_ID),
CUR AS (
  SELECT PLANT_ID, SUM(AVAILABLE_QTY) QTY, SUM(INVENTORY_VALUE_INR) VAL, COUNT(*) LINES
    FROM VEDANTA_POC.INVENTORY_CLASSIFICATION WHERE AS_OF_DATE = '2025-12-31' GROUP BY PLANT_ID),
KPI AS (
  SELECT PLANT_ID, SUM(KPI_VALUE) VAL FROM VEDANTA_POC.INVENTORY_KPI_MONTHLY
   WHERE KPI_CODE='GROSS_INVENTORY_VALUE_INR' AND POSTING_MONTH='2025-12' GROUP BY PLANT_ID)
SELECT COALESCE(R.PLANT_ID,C.PLANT_ID,K.PLANT_ID) AS PLANT,
       R.LINES RAW_LINES, R.QTY RAW_QTY, R.VAL RAW_VAL,
       C.LINES CUR_LINES, C.QTY CUR_QTY, C.VAL CUR_VAL, K.VAL KPI_VAL
  FROM RAWV R FULL JOIN CUR C ON R.PLANT_ID = C.PLANT_ID
              FULL JOIN KPI K ON K.PLANT_ID = COALESCE(R.PLANT_ID, C.PLANT_ID)
 ORDER BY 1;

