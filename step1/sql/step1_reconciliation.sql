-- R2. Movement counts by movement type, in scope (RAW only — no curated equivalent).
------------------------------------------------------------------------------
WITH MM AS (
  SELECT MATERIAL_ID, MOVEMENT_TYPE, QUANTITY, POSTING_DATE, IS_BACKCAST_PERIOD FROM VEDANTA_POC.FACT_MATERIAL_MOVEMENT_PART_001
  UNION ALL SELECT MATERIAL_ID, MOVEMENT_TYPE, QUANTITY, POSTING_DATE, IS_BACKCAST_PERIOD FROM VEDANTA_POC.FACT_MATERIAL_MOVEMENT_PART_002
  UNION ALL SELECT MATERIAL_ID, MOVEMENT_TYPE, QUANTITY, POSTING_DATE, IS_BACKCAST_PERIOD FROM VEDANTA_POC.FACT_MATERIAL_MOVEMENT_PART_003
  UNION ALL SELECT MATERIAL_ID, MOVEMENT_TYPE, QUANTITY, POSTING_DATE, IS_BACKCAST_PERIOD FROM VEDANTA_POC.FACT_MATERIAL_MOVEMENT_PART_004)
SELECT M.MOVEMENT_TYPE, COUNT(*) LINES, SUM(TO_DECIMAL(M.QUANTITY,18,3)) QTY
  FROM MM M JOIN VEDANTA_POC.DIM_MATERIAL D ON D.MATERIAL_ID = M.MATERIAL_ID
 WHERE D.MATERIAL_TYPE IN ('ZSPR','ZSPN') AND M.IS_BACKCAST_PERIOD='N'
   AND M.POSTING_DATE BETWEEN '2024-01-01' AND '2025-12-31'
 GROUP BY M.MOVEMENT_TYPE ORDER BY 2 DESC;

------------------------------------------------------------------------------
-- R3. Movement-class counts: CURATED INVENTORY_CLASSIFICATION.MOVEMENT_CLASS
--     vs RAW recomputation of the brief's rule
--     (ACTIVE<=90d, SM<=180d, NM<=365d, OBS>365d, never-issued=NM) from last 261.
------------------------------------------------------------------------------
WITH MM AS (
  SELECT MATERIAL_ID, PLANT_ID, MOVEMENT_TYPE, POSTING_DATE, IS_BACKCAST_PERIOD FROM VEDANTA_POC.FACT_MATERIAL_MOVEMENT_PART_001
  UNION ALL SELECT MATERIAL_ID, PLANT_ID, MOVEMENT_TYPE, POSTING_DATE, IS_BACKCAST_PERIOD FROM VEDANTA_POC.FACT_MATERIAL_MOVEMENT_PART_002
  UNION ALL SELECT MATERIAL_ID, PLANT_ID, MOVEMENT_TYPE, POSTING_DATE, IS_BACKCAST_PERIOD FROM VEDANTA_POC.FACT_MATERIAL_MOVEMENT_PART_003
  UNION ALL SELECT MATERIAL_ID, PLANT_ID, MOVEMENT_TYPE, POSTING_DATE, IS_BACKCAST_PERIOD FROM VEDANTA_POC.FACT_MATERIAL_MOVEMENT_PART_004),
LASTC AS (
  SELECT M.MATERIAL_ID, M.PLANT_ID, MAX(TO_DATE(M.POSTING_DATE)) LCD
    FROM MM M JOIN VEDANTA_POC.DIM_MATERIAL D ON D.MATERIAL_ID=M.MATERIAL_ID
   WHERE D.MATERIAL_TYPE IN ('ZSPR','ZSPN') AND M.IS_BACKCAST_PERIOD='N'
     AND M.MOVEMENT_TYPE='261' AND M.POSTING_DATE <= '2025-12-31'
   GROUP BY M.MATERIAL_ID, M.PLANT_ID),
BASE AS (
  SELECT C.MOVEMENT_CLASS CUR_CLASS,
         CASE WHEN L.LCD IS NULL                                     THEN 'NON_MOVING'
              WHEN DAYS_BETWEEN(L.LCD, DATE'2025-12-31') <=  90      THEN 'ACTIVE'
              WHEN DAYS_BETWEEN(L.LCD, DATE'2025-12-31') <= 180      THEN 'SLOW_MOVING'
              WHEN DAYS_BETWEEN(L.LCD, DATE'2025-12-31') <= 365      THEN 'NON_MOVING'
              ELSE 'OBSOLETE' END AS RAW_CLASS
    FROM VEDANTA_POC.INVENTORY_CLASSIFICATION C
    LEFT JOIN LASTC L ON L.MATERIAL_ID=C.MATERIAL_ID AND L.PLANT_ID=C.PLANT_ID
   WHERE C.AS_OF_DATE='2025-12-31')
SELECT COALESCE(A.CLS,B.CLS) MOVEMENT_CLASS, A.N CURATED_N, B.N RAW_N, COALESCE(A.N,0)-COALESCE(B.N,0) DIFF
  FROM (SELECT CUR_CLASS CLS, COUNT(*) N FROM BASE GROUP BY CUR_CLASS) A
  FULL JOIN (SELECT RAW_CLASS CLS, COUNT(*) N FROM BASE GROUP BY RAW_CLASS) B ON A.CLS=B.CLS
 ORDER BY 1;

------------------------------------------------------------------------------
-- R4. ROP and trailing-12m demand: CURATED columns vs RAW recomputation
--     RAW_ROP = trailing-12m net demand / 365 * PLANNED_DELIVERY_DAYS + curated safety stock.
--     Also tests whether curated T12 is NET (261-262) or ISSUES-ONLY (261).
------------------------------------------------------------------------------
WITH MM AS (
  SELECT MATERIAL_ID, PLANT_ID, MOVEMENT_TYPE, QUANTITY, POSTING_DATE, IS_BACKCAST_PERIOD FROM VEDANTA_POC.FACT_MATERIAL_MOVEMENT_PART_001
  UNION ALL SELECT MATERIAL_ID, PLANT_ID, MOVEMENT_TYPE, QUANTITY, POSTING_DATE, IS_BACKCAST_PERIOD FROM VEDANTA_POC.FACT_MATERIAL_MOVEMENT_PART_002
  UNION ALL SELECT MATERIAL_ID, PLANT_ID, MOVEMENT_TYPE, QUANTITY, POSTING_DATE, IS_BACKCAST_PERIOD FROM VEDANTA_POC.FACT_MATERIAL_MOVEMENT_PART_003
  UNION ALL SELECT MATERIAL_ID, PLANT_ID, MOVEMENT_TYPE, QUANTITY, POSTING_DATE, IS_BACKCAST_PERIOD FROM VEDANTA_POC.FACT_MATERIAL_MOVEMENT_PART_004),
A AS (
  SELECT M.MATERIAL_ID, M.PLANT_ID,
         SUM(CASE WHEN M.MOVEMENT_TYPE='261' THEN TO_DECIMAL(M.QUANTITY,18,3) ELSE 0 END) ISS_ONLY,
         SUM(CASE WHEN M.MOVEMENT_TYPE='261' THEN  TO_DECIMAL(M.QUANTITY,18,3)
                                             ELSE -TO_DECIMAL(M.QUANTITY,18,3) END)        NETQ
    FROM MM M JOIN VEDANTA_POC.DIM_MATERIAL D ON D.MATERIAL_ID=M.MATERIAL_ID
   WHERE D.MATERIAL_TYPE IN ('ZSPR','ZSPN') AND M.IS_BACKCAST_PERIOD='N'
     AND M.MOVEMENT_TYPE IN ('261','262')
     AND M.POSTING_DATE BETWEEN '2025-01-01' AND '2025-12-31'
   GROUP BY M.MATERIAL_ID, M.PLANT_ID)
SELECT COUNT(*) N,
       SUM(C.TRAILING_12M_DEMAND_QTY)                                            CUR_T12_SUM,
       SUM(COALESCE(A.NETQ,0))                                                   RAW_T12_NET_SUM,
       SUM(COALESCE(A.ISS_ONLY,0))                                               RAW_T12_ISSUES_SUM,
       SUM(CASE WHEN ABS(C.TRAILING_12M_DEMAND_QTY-COALESCE(A.NETQ,0))<=0.01 THEN 1 ELSE 0 END)     MATCH_NET,
       SUM(CASE WHEN ABS(C.TRAILING_12M_DEMAND_QTY-COALESCE(A.ISS_ONLY,0))<=0.01 THEN 1 ELSE 0 END) MATCH_ISSUES_ONLY,
       SUM(C.REORDER_POINT_QTY)                                                  CUR_ROP_SUM,
       SUM(COALESCE(A.NETQ,0)/365.0*TO_DECIMAL(D.PLANNED_DELIVERY_DAYS,18,2)+C.SAFETY_STOCK_QTY) RAW_ROP_SUM,
       SUM(CASE WHEN C.REORDER_POINT_QTY=0 OR
                     ABS(C.REORDER_POINT_QTY-(COALESCE(A.NETQ,0)/365.0*TO_DECIMAL(D.PLANNED_DELIVERY_DAYS,18,2)+C.SAFETY_STOCK_QTY))
                     /NULLIF(ABS(C.REORDER_POINT_QTY),0) <= 0.20 THEN 1 ELSE 0 END) ROP_WITHIN_20PCT
  FROM VEDANTA_POC.INVENTORY_CLASSIFICATION C
  JOIN VEDANTA_POC.DIM_MATERIAL D ON D.MATERIAL_ID = C.MATERIAL_ID
  LEFT JOIN A ON A.MATERIAL_ID=C.MATERIAL_ID AND A.PLANT_ID=C.PLANT_ID
 WHERE C.AS_OF_DATE='2025-12-31';
