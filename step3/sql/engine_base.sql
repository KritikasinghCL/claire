-- Step 3 engine: per material-plant line, computed IN HANA. Read-only.
-- Master rules: MC ACTIVE<=90 / SM<=180 / NM<=365 / OBS>365, never-issued=NM
--               service VITAL 98 (z=2.054) ESSENTIAL 95 (1.645) DESIRABLE 90 (1.282)
--               lead time = MAX(planned, actual median PO->GR) + median PR->PO (24d)
--               SS = z * sigma_monthly * sqrt(LT/30.44)   [sigma zero-filled over 24 months]
--               ROP = lead-time demand + SS ; MAX = ROP + 3-month forecast
--               overstock = stock > max(MAX, 12-month forecast) ; holding cost 8%
WITH MV AS (
  SELECT MATERIAL_ID,PLANT_ID,MOVEMENT_TYPE,TO_DECIMAL(QUANTITY,18,3) Q,SUBSTRING(POSTING_DATE,1,7) YM,TO_DATE(POSTING_DATE) PD
    FROM VEDANTA_POC.FACT_MATERIAL_MOVEMENT_PART_001
   WHERE IS_BACKCAST_PERIOD='N' AND MOVEMENT_TYPE IN ('261','262') AND POSTING_DATE BETWEEN '2024-01-01' AND '2025-12-31'
  UNION ALL SELECT MATERIAL_ID,PLANT_ID,MOVEMENT_TYPE,TO_DECIMAL(QUANTITY,18,3),SUBSTRING(POSTING_DATE,1,7),TO_DATE(POSTING_DATE)
    FROM VEDANTA_POC.FACT_MATERIAL_MOVEMENT_PART_002
   WHERE IS_BACKCAST_PERIOD='N' AND MOVEMENT_TYPE IN ('261','262') AND POSTING_DATE BETWEEN '2024-01-01' AND '2025-12-31'
  UNION ALL SELECT MATERIAL_ID,PLANT_ID,MOVEMENT_TYPE,TO_DECIMAL(QUANTITY,18,3),SUBSTRING(POSTING_DATE,1,7),TO_DATE(POSTING_DATE)
    FROM VEDANTA_POC.FACT_MATERIAL_MOVEMENT_PART_003
   WHERE IS_BACKCAST_PERIOD='N' AND MOVEMENT_TYPE IN ('261','262') AND POSTING_DATE BETWEEN '2024-01-01' AND '2025-12-31'
  UNION ALL SELECT MATERIAL_ID,PLANT_ID,MOVEMENT_TYPE,TO_DECIMAL(QUANTITY,18,3),SUBSTRING(POSTING_DATE,1,7),TO_DATE(POSTING_DATE)
    FROM VEDANTA_POC.FACT_MATERIAL_MOVEMENT_PART_004
   WHERE IS_BACKCAST_PERIOD='N' AND MOVEMENT_TYPE IN ('261','262') AND POSTING_DATE BETWEEN '2024-01-01' AND '2025-12-31'
),
MM AS (SELECT MATERIAL_ID,PLANT_ID,YM,SUM(CASE WHEN MOVEMENT_TYPE='261' THEN Q ELSE -Q END) NETM
         FROM MV GROUP BY MATERIAL_ID,PLANT_ID,YM),
AGG AS (SELECT MATERIAL_ID,PLANT_ID,
               SUM(NETM) NET24, SUM(CASE WHEN YM>='2025-01' THEN NETM ELSE 0 END) NET12,
               SUM(POWER(NETM,2)) SQ24, COUNT(*) NMONTHS
          FROM MM GROUP BY MATERIAL_ID,PLANT_ID),
ALT AS (SELECT pr.MATERIAL_ID, MEDIAN(DAYS_BETWEEN(po.PD,gr.GD)) ALT_D
          FROM (SELECT PR_NUMBER,PR_ITEM,MATERIAL_ID FROM VEDANTA_POC.FACT_PURCHASE_REQUISITION WHERE IS_BACKCAST_PERIOD='N') pr
          JOIN (SELECT PR_NUMBER,PR_ITEM,PO_NUMBER,PO_ITEM,TO_DATE(PO_DATE) PD FROM VEDANTA_POC.FACT_PURCHASE_ORDER WHERE IS_BACKCAST_PERIOD='N') po
            ON pr.PR_NUMBER=po.PR_NUMBER AND pr.PR_ITEM=po.PR_ITEM
          JOIN (SELECT PO_NUMBER,PO_ITEM,TO_DATE(POSTING_DATE) GD FROM VEDANTA_POC.FACT_GOODS_RECEIPT WHERE IS_BACKCAST_PERIOD='N') gr
            ON po.PO_NUMBER=gr.PO_NUMBER AND po.PO_ITEM=gr.PO_ITEM
         GROUP BY pr.MATERIAL_ID),
OPEN_PR AS (SELECT MATERIAL_ID,PLANT_ID,SUM(TO_DECIMAL(REQUESTED_QTY,18,3)) OPEN_PR_QTY
              FROM VEDANTA_POC.FACT_PURCHASE_REQUISITION
             WHERE IS_BACKCAST_PERIOD='N' AND STATUS <> 'CONVERTED' GROUP BY MATERIAL_ID,PLANT_ID),
L AS (
  SELECT ic.MATERIAL_ID MID, ic.PLANT_ID P, dm.MATERIAL_GROUP MG, dm.MATERIAL_TYPE MT,
         ic.CRITICALITY CR, dm.SHUTDOWN_MATERIAL_FLAG SD, cm.BUSINESS_CATEGORY CAT,
         ic.AVAILABLE_QTY AQ, ic.INVENTORY_VALUE_INR IV, TO_DECIMAL(dm.UNIT_COST_INR,18,2) UC,
         ic.DAYS_SINCE_LAST_CONSUMPTION DSLC, ic.LAST_CONSUMPTION_DATE LCD,
         ic.MOVEMENT_CLASS SAP_MC, ic.SAFETY_STOCK_QTY SAP_SS, ic.REORDER_POINT_QTY SAP_ROP, ic.MAX_STOCK_QTY SAP_MAX,
         TO_DECIMAL(dm.MIN_ORDER_QTY,18,3) MOQ, TO_DECIMAL(dm.ORDER_MULTIPLE,18,3) OM,
         COALESCE(a.NET12,0) NET12, COALESCE(a.NET24,0) NET24,
         SQRT(GREATEST(COALESCE(a.SQ24,0)/24.0 - POWER(COALESCE(a.NET24,0)/24.0,2),0)) SIG_M,   -- zero-filled 24m sigma
         GREATEST(TO_DECIMAL(dm.PLANNED_DELIVERY_DAYS,18,3), COALESCE(lt.ALT_D,0)) + 24 LT,      -- +24d median PR->PO
         COALESCE(o.OPEN_PR_QTY,0) OPEN_PR,
         CASE WHEN ic.LAST_CONSUMPTION_DATE IS NULL THEN 'NON_MOVING'
              WHEN ic.DAYS_SINCE_LAST_CONSUMPTION<=90  THEN 'ACTIVE'
              WHEN ic.DAYS_SINCE_LAST_CONSUMPTION<=180 THEN 'SLOW_MOVING'
              WHEN ic.DAYS_SINCE_LAST_CONSUMPTION<=365 THEN 'NON_MOVING'
              ELSE 'OBSOLETE' END MC,
         CASE ic.CRITICALITY WHEN 'VITAL' THEN 2.054 WHEN 'ESSENTIAL' THEN 1.645 ELSE 1.282 END Z
    FROM VEDANTA_POC.INVENTORY_CLASSIFICATION ic
    JOIN VEDANTA_POC.DIM_MATERIAL dm ON dm.MATERIAL_ID=ic.MATERIAL_ID
    LEFT JOIN VEDANTA_POC.CATEGORY_MAP cm ON cm.MATERIAL_GROUP=dm.MATERIAL_GROUP
    LEFT JOIN AGG a  ON a.MATERIAL_ID=ic.MATERIAL_ID AND a.PLANT_ID=ic.PLANT_ID
    LEFT JOIN ALT lt ON lt.MATERIAL_ID=ic.MATERIAL_ID
    LEFT JOIN OPEN_PR o ON o.MATERIAL_ID=ic.MATERIAL_ID AND o.PLANT_ID=ic.PLANT_ID
   WHERE ic.AS_OF_DATE='2025-12-31' AND dm.MATERIAL_TYPE IN ('ZSPR','ZSPN')
),
E AS (
  SELECT L.*,
         GREATEST(NET12,0)/365.0 DD,
         Z*SIG_M*SQRT(LT/30.44) SS,
         GREATEST(NET12,0)/365.0*LT + Z*SIG_M*SQRT(LT/30.44) ROP,
         GREATEST(NET12,0)/12.0*3  F3,
         GREATEST(NET12,0)         F12
    FROM L
),
F AS (SELECT E.*, ROP + F3 MX, GREATEST(ROP + F3, F12) OVER_THRESH FROM E)
SELECT * FROM F;
